class Command(BaseCommand):
    help = "Populate the database with the project's saved skills, schools, and courses."

    @transaction.atomic
    def handle(self, *args, **options):
        self._upsert(Skill, SKILLS)
        self._upsert(School, SCHOOLS)
        self._upsert(Course, COURSES)
        self._upsert(SchoolSkill, SCHOOL_SKILLS)

        for item in SKILL_RELATIONS:
            Skill.objects.get(pk=item["pk"]).related_skills.set(item["related_skills"])

        for item in COURSE_RELATIONS:
            Course.objects.get(pk=item["pk"]).skills.set(item["skills"])

        models = [Skill, School, Course, SchoolSkill]
        with connection.cursor() as cursor:
            for sql in connection.ops.sequence_reset_sql(no_style(), models):
                cursor.execute(sql)

        total = sum(len(records) for records in (SKILLS, SCHOOLS, COURSES, SCHOOL_SKILLS))
        self.stdout.write(self.style.SUCCESS(f"Loaded {total} saved objects."))

    @staticmethod
    def _upsert(model, records):
        objects = [model(pk=record["pk"], **{key: value for key, value in record.items() if key != "pk"}) for record in records]
        primary_keys = [item.pk for item in objects]
        existing_keys = set(model.objects.filter(pk__in=primary_keys).values_list("pk", flat=True))
        new_objects = [item for item in objects if item.pk not in existing_keys]
        existing_objects = [item for item in objects if item.pk in existing_keys]

        model.objects.bulk_create(new_objects)
        for item in existing_objects:
            values = {
                field.attname: getattr(item, field.attname)
                for field in model._meta.concrete_fields
                if not field.primary_key and field.name not in {"created_at", "updated_at"}
            }
            model.objects.filter(pk=item.pk).update(**values)
